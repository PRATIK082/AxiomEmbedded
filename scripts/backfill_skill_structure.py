"""Backfill baseline checklists + standard-maps for thin skills.

One-time structure migration (idempotent): for every skill under skills/
that has SKILL.md + manifest.yaml but no checklists/ dir, generate:

- checklists/<sid>-checklist.md — review gates derived mechanically from
  the SKILL.md body's `##` section headings (no invented content).
- references/standard-map.md — table built from manifest.yaml
  `standards_refs` (number/version/clause only, no normative text).

Never overwrites existing files. Never touches SKILL.md or manifest.yaml.
Usage: python scripts/backfill_skill_structure.py
"""
from __future__ import annotations

import pathlib
import re
import sys

try:
    import yaml
except ImportError:  # pragma: no cover
    yaml = None

ROOT = pathlib.Path(__file__).resolve().parents[1]
GEN = "<!-- Generated by scripts/backfill_skill_structure.py — baseline only. Edit freely; reruns never overwrite. -->"

FRONT_RE = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def split_frontmatter(text: str) -> tuple[dict, str]:
    m = FRONT_RE.match(text)
    if not m or yaml is None:
        return {}, text
    try:
        return yaml.safe_load(m.group(1)) or {}, text[m.end():]
    except yaml.YAMLError:
        return {}, text


def headings(body: str, limit: int = 12) -> list[str]:
    out = []
    for line in body.splitlines():
        if line.startswith("## "):
            out.append(line[3:].strip())
        if len(out) >= limit:
            break
    return out


def checklist_md(sid: str, front: dict, body_heads: list[str]) -> str:
    title = str(front.get("name", sid)).replace("-", " ").title()
    lines = [GEN, f"# {title} checklist", ""]
    for h in body_heads:
        lines.append(f"- [ ] Section `{h}` addressed with project evidence")
    lines += [
        "- [ ] Assumptions, evidence links, and open questions recorded",
        "- [ ] No normative text copied from standards; citations are number/edition/clause only",
        "- [ ] Traceability links to related artifacts recorded (or N/A with reason)",
        "",
    ]
    return "\n".join(lines)


def standard_map_md(sid: str, manifest: dict) -> str:
    lines = [GEN, f"# Standard map — {sid} (original summaries, no normative text)", ""]
    refs = manifest.get("standards_refs") or []
    if refs:
        lines += ["| Standard | Edition | Clauses considered | Project use |",
                  "|---|---|---|---|"]
        for r in refs:
            num = str(r.get("number", "?")).replace("|", "/")
            ver = str(r.get("version", "")).replace("|", "/")
            clause = str(r.get("clause", "")).replace("|", "/").replace("\n", " ")
            lines.append(f"| {num} | {ver} | {clause} | Recorded per artifact assumptions |")
    else:
        lines.append("No normative references declared in manifest.yaml; see SKILL.md for guidance.")
    lines += ["",
              "- Cite number, title, edition/year, clause only. Summaries are original language.",
              "- Official sources only. Mandatory vs recommended vs project decision are",
              "  recorded separately in the artifact assumptions.",
              ""]
    return "\n".join(lines)


def main() -> int:
    made = {"checklists": 0, "maps": 0, "skipped": 0}
    for d in sorted((ROOT / "skills").iterdir()):
        if not d.is_dir() or d.name.startswith(("_", ".")):
            continue
        md, mp = d / "SKILL.md", d / "manifest.yaml"
        if not (md.exists() and mp.exists()):
            continue
        if (d / "checklists").is_dir() and (d / "references").is_dir():
            made["skipped"] += 1
            continue
        front, body = split_frontmatter(md.read_text(encoding="utf-8"))
        manifest = yaml.safe_load(mp.read_text(encoding="utf-8")) or {} if yaml else {}
        cl_dir, ref_dir = d / "checklists", d / "references"
        cl_file = cl_dir / f"{d.name}-checklist.md"
        map_file = ref_dir / "standard-map.md"
        if not cl_file.exists():
            cl_dir.mkdir(exist_ok=True)
            cl_file.write_text(checklist_md(d.name, front, headings(body)), encoding="utf-8")
            made["checklists"] += 1
        if not map_file.exists():
            ref_dir.mkdir(exist_ok=True)
            map_file.write_text(standard_map_md(d.name, manifest), encoding="utf-8")
            made["maps"] += 1
    print(made)
    return 0


if __name__ == "__main__":
    sys.exit(main())
