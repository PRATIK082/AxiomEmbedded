EVALS_JSON = [
    {"id": "E01", "name": "happy path", "input": "repository path, objective, constraints",
     "expected": "run report + manifest produced, no errors"},
    {"id": "E02", "name": "missing inputs", "input": "repository path only",
     "expected": "clarification requested, no invented defaults"},
    {"id": "E03", "name": "dry-run no writes", "input": "dry_run=true",
     "expected": "no files written outside output dir"},
]


def backfill(dry_run: bool = True) -> dict:
    stats = {"validate_py": 0, "references": 0, "templates": 0, "tests": 0, "checklists": 0}
    for d in sorted(SKILLS.iterdir()):
        if not d.is_dir() or d.name.startswith("_"):
            continue
        sid = d.name
        title = sid.replace("-", " ").title()
        # validate.py
        vp = d / "scripts" / "validate.py"
        if not vp.exists():
            stats["validate_py"] += 1
            if not dry_run:
                (d / "scripts").mkdir(exist_ok=True)
                vp.write_text(VALIDATE_PY.format(sid=sid), encoding="utf-8")
        # references
        ref_dir = d / "references"
        if not ref_dir.exists() or not any(ref_dir.iterdir()):
            stats["references"] += 1
            if not dry_run:
                ref_dir.mkdir(exist_ok=True)
                (ref_dir / "overview.md").write_text(
                    REFERENCE_MD.format(title=title, sid=sid), encoding="utf-8")
        # templates
        tpl_dir = d / "templates"
        if not tpl_dir.exists() or not any(tpl_dir.iterdir()):
            stats["templates"] += 1
            if not dry_run:
                tpl_dir.mkdir(exist_ok=True)
                (tpl_dir / "artifact.template.md").write_text(
                    TEMPLATE_MD.format(title=title, sid=sid), encoding="utf-8")
        # tests
        test_dir = d / "tests"
        if not test_dir.exists() or not any(test_dir.iterdir()):
            stats["tests"] += 1
            if not dry_run:
                test_dir.mkdir(exist_ok=True)
                (test_dir / "evals.json").write_text(
                    json.dumps(EVALS_JSON, indent=2), encoding="utf-8")
        # checklists
        ck_dir = d / "checklists"
        if not ck_dir.exists() or not any(ck_dir.iterdir()):
            stats["checklists"] += 1
            if not dry_run:
                ck_dir.mkdir(exist_ok=True)
                (ck_dir / "review.yaml").write_text(
                    "gates:\n  - id: scope\n    text: Scope recorded\n"
                    "  - id: validate\n    text: Validation green\n",
                    encoding="utf-8")
    return stats


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", default=True)
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    dry = not args.apply
    stats = backfill(dry)
    print(f"mode={'dry-run' if dry else 'apply'}")
    for k, v in stats.items():
        print(f"  {k}: {v} skills need backfill")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
